          const card = h(`<div class="panel vcard">${head}<div class="muted small">What does it mean?</div><div class="choices">${opts.map((o, i) => `<button type="button" class="choice" data-i="${i}"><span class="bub">${LET[i]}</span><span>${esc(o.def)}</span></button>`).join('')}</div><div id="vres"></div></div>`);
